// node lib/__tests__/signal.test.mjs
//
// SIGNAL (Jon, 2026-11-20: "the most important things that need to be completed vs busy work").
// The tier, the priority rule and the score are read by the Glitches board, the briefs, Blocked
// units, the Listing desk, the inbox and the calls desk, so the rules are pinned here once.
// Plain node: lib/signal.ts has no imports and node >= 22.18 strips the types.
const S = await import('../signal.ts')

let pass = 0, fail = 0
const ok = (name, cond, extra = '') => { if (cond) pass++; else { fail++; console.log('  FAIL  ' + name + (extra ? '  ' + extra : '')) } }
const eq = (name, got, want) => ok(name, JSON.stringify(got) === JSON.stringify(want), 'got ' + JSON.stringify(got) + ' want ' + JSON.stringify(want))

console.log('\nproperty tier: by the building\'s nightly rate')
eq('rate is fare / nights, whole dollars', S.nightlyRate(2423804, 7687), 315)
eq('no nights sold → no rate', S.nightlyRate(0, 0), null)
const t = (o) => { const r = S.tierFor(o); return [r.tier, r.source] }
eq('17WEST $315 → High by rate', t({ building: '17WEST', revenue: 2423804, nights: 7687 }), ['high', 'rate'])
eq('Elser $160 → High by rate', t({ building: 'Elser', revenue: 792798, nights: 4952, lux: true }), ['high', 'rate'])
eq('exactly $150 is High', t({ building: 'X', revenue: 15000, nights: 100 }), ['high', 'rate'])
eq('$149 is Standard', t({ building: 'X', revenue: 14900, nights: 100 }), ['standard', 'rate'])
eq('Eden $84 → Standard by rate', t({ building: 'Eden', revenue: 588126, nights: 7035 }), ['standard', 'rate'])
eq('Nomad $103 is High by the lux flag', t({ building: 'Nomad', revenue: 10564, nights: 103, lux: true }), ['high', 'flag'])
eq('a new lux building with no stays is High by flag', t({ building: 'New Tower', revenue: 0, nights: 0, lux: true }), ['high', 'flag'])
eq('a new building with no stays and no flag is Standard, source none', t({ building: 'The Crosby', revenue: 0, nights: 0 }), ['standard', 'none'])
eq('under 100 nights the rate does not decide', t({ building: 'Surfside', revenue: 50000, nights: 50 }), ['standard', 'none'])
eq('Botanica is Partner', t({ building: 'Botanica', revenue: 470151, nights: 6809 }), ['partner', 'partner'])
eq('Hendricks is pinned Standard', t({ building: 'Hendricks', revenue: 197456, nights: 2030 }), ['standard', 'override'])
eq('3316 stays Standard even if its rate crosses the line', t({ building: '3316', revenue: 80000, nights: 500 }), ['standard', 'override'])
eq('the setting beats the pinned default', t({ building: 'Park Towers', revenue: 77855, nights: 1137, overrides: { 'park towers': 'high' } }), ['high', 'override'])
eq('the setting can force a High building down', t({ building: '17WEST', revenue: 2423804, nights: 7687, overrides: { '17 West': 'standard' } }), ['standard', 'override'])
eq('a junk override is ignored', t({ building: 'Eden', revenue: 588126, nights: 7035, overrides: { Eden: 'gold' } }), ['standard', 'rate'])

console.log('\npriority booking')
const rules = { bigBookingUsd: 3000, longStayNights: 14 }
const P = (b, o) => S.priorityOf(b, rules, o)
ok('an ordinary booking is not priority', !P({ source: 'airbnb2', total: 1474, nights: 5 }).priority)
eq('owner by source', P({ source: 'owner-guest', total: 0, nights: 3 }).why, ['owner'])
eq('$3,000 is big', P({ total: 3000, nights: 4 }).why, ['big'])
ok('$2,999 is not', !P({ total: 2999, nights: 4 }).priority)
eq('14 nights is long', P({ total: 900, nights: 14 }).why, ['long'])
eq('sensitive, VIP and repeat each count', [P({ sensitive: true }).priority, P({ vip: true }).priority, P({ repeat: true }).priority], [true, true, true])
eq('reasons read in plain words', P({ source: 'owner', total: 5000, repeat: true }).label, 'owner stay, big booking, repeat guest')
ok('the Glitches board can leave Sensitive out', !P({ sensitive: true }, { ignoreSensitive: true }).priority)
ok('…but VIP still counts there', P({ sensitive: true, vip: true }, { ignoreSensitive: true }).priority)
eq('the thresholds come from the settings passed in', S.priorityOf({ total: 2000, nights: 7 }, { bigBookingUsd: 1500, longStayNights: 7 }).why, ['big', 'long'])
eq('no settings → the defaults', S.priorityOf({ total: 3000 }, null).why, ['big'])

console.log('\npriority at risk')
ok('a 2-star in the last five', S.hasLowReview([5, 5, 2, 5]))
ok('a 3-star is not low', !S.hasLowReview([3, 4, 5]))
ok('only the last five are read', !S.hasLowReview([5, 5, 5, 5, 5, 1]))
ok('a missing rating is not a zero', !S.hasLowReview([null, '', undefined]))
const af = (b, r) => S.arrivalFlag(b, r, rules)
eq('priority + same-day turn', af({ total: 4000 }, { sameDayTurn: true }).tag, 'Priority at risk')
eq('priority, nothing wrong', af({ total: 4000 }, {}).tag, 'Priority')
eq('a risk on an ordinary booking is not flagged', af({ total: 800 }, { sameDayTurn: true, openGlitch: true }).tag, '')
eq('the reason names both halves', af({ repeat: true }, { openGlitch: true, lowReview: true }).reason, 'repeat guest · open glitch, recent low review')
const arr = [af({ total: 800 }, {}), af({ total: 4000 }, {}), af({ total: 4000 }, { lowReview: true })].map(x => x.rank)
eq('at risk leads, then priority, then the rest', arr.slice().sort((a, b) => a - b), [0, 1, 2])

console.log('\nthe score: guest impact (0-35)')
const sc = (i) => S.signalScore(i)
eq('in house and they told us', sc({ guest: 'in_house', guestReported: true }).parts.guest, 35)
eq('arriving today', sc({ guest: 'arriving_today' }).parts.guest, 30)
eq('in house, field-noted', sc({ guest: 'in_house' }).parts.guest, 20)
eq('arriving within three days', sc({ guest: 'arriving_soon', arrivesInDays: 2 }).parts.guest, 15)
eq('nobody', sc({}).parts.guest, 0)

console.log('\nthe score: money at stake (0-35)')
eq('fare x nights left', sc({ guest: 'in_house', nightlyFare: 249, nightsExposed: 6 }).stakeUsd, 1494)
eq('one point per $60', sc({ guest: 'in_house', nightlyFare: 249, nightsExposed: 6 }).parts.money, 25)
eq('seven nights at most', sc({ guest: 'in_house', nightlyFare: 100, nightsExposed: 104 }).stakeUsd, 700)
eq('capped at 35', sc({ guest: 'in_house', nightlyFare: 800, nightsExposed: 7 }).parts.money, 35)
eq('the building rate stands in for an unknown fare', sc({ guest: 'arriving_today', rate: 315, nightsExposed: 2 }).stakeUsd, 630)
eq('money named outright wins when larger', sc({ guest: 'in_house', nightlyFare: 50, nightsExposed: 1, stakeUsd: 400 }).stakeUsd, 400)
eq('no guest → no exposure', sc({ rate: 315, nightsExposed: 5 }).stakeUsd, 0)

console.log('\nthe score: the clock (0-20) and priority (10)')
eq('overdue', sc({ dueInDays: -6 }).parts.clock, 20)
eq('due today', sc({ dueInDays: 0 }).parts.clock, 20)
eq('due in two days', sc({ dueInDays: 2 }).parts.clock, 10)
eq('due in three', sc({ dueInDays: 3 }).parts.clock, 0)
eq('urgent with no due date', sc({ urgent: true }).parts.clock, 20)
eq('a priority booking adds ten', sc({ priority: true }).parts.priority, 10)
eq('the sum (the 17WEST 510 card of 2026-11-20)', sc({ guest: 'in_house', guestReported: true, nightlyFare: 249, nightsExposed: 6, dueInDays: -6, priority: true }).score, 90)
ok('never over 100', sc({ guest: 'in_house', guestReported: true, nightlyFare: 900, nightsExposed: 7, dueInDays: -1, priority: true }).score === 100)

console.log('\nthe floor: a money deadline inside 48 hours')
const claim = sc({ building: '17WEST', rate: 315, moneyDeadlineHours: 20 })
eq('a claim due tomorrow with no amount ranks at the floor', [claim.score, claim.floored, claim.line], [70, true, 'work'])
eq('49 hours out gets the clock, not the floor', [sc({ moneyDeadlineHours: 49 }).score, sc({ moneyDeadlineHours: 49 }).floored], [10, false])
ok('a passed deadline is not floored', !sc({ moneyDeadlineHours: -5 }).floored)
const hot = sc({ guest: 'in_house', guestReported: true, nightlyFare: 300, nightsExposed: 7, dueInDays: -1, moneyDeadlineHours: 10 })
ok('the floor never lowers a higher score', hot.score > 70 && !hot.floored)

console.log('\nrevenue leaks and partners')
const leak = sc({ building: 'Eden', rate: 84, weeklyUsd: 543, dueInDays: null })
eq('no guest + dollars a week = the leaks line', [leak.line, leak.weeklyUsd], ['leak', 543])
eq('a guest keeps it on the work line', sc({ guest: 'in_house', weeklyUsd: 543 }).line, 'work')
const part = sc({ building: 'Botanica', tier: 'partner', guest: 'in_house', guestReported: true, dueInDays: -3 })
eq('a partner property is never ranked', [part.ranked, part.score, part.line], [false, 0, 'partner'])
const leaks = [{ key: 'a', signal: sc({ weeklyUsd: 300, tier: 'standard' }) }, { key: 'b', signal: sc({ weeklyUsd: 900, tier: 'standard' }) }, { key: 'c', signal: sc({ weeklyUsd: 300, tier: 'high' }) }]
eq('leaks: most dollars a week, then the High building', leaks.sort(S.compareLeaks).map(x => x.key), ['b', 'c', 'a'])

console.log('\ntie-breaks')
const row = (key, i) => ({ key, signal: sc(i) })
const same = { guest: 'in_house', dueInDays: -1 }
eq('score first', [row('a', { guest: 'arriving_soon' }), row('b', { guest: 'in_house', guestReported: true })].sort(S.compareSignal).map(x => x.key), ['b', 'a'])
eq('then dollars at stake', [row('a', { ...same, guestReported: true, nightlyFare: 40, nightsExposed: 1, stakeUsd: 10 }), row('b', { ...same, guestReported: true, nightlyFare: 40, nightsExposed: 1, stakeUsd: 55 })].sort(S.compareSignal).map(x => x.key), ['b', 'a'])
eq('then the higher nightly rate', [row('a', { ...same, rate: 84 }), row('b', { ...same, rate: 315 })].sort(S.compareSignal).map(x => x.key), ['b', 'a'])
eq('then the older due date', [row('a', { guest: 'in_house', dueInDays: -1 }), row('b', { guest: 'in_house', dueInDays: -9 })].sort(S.compareSignal).map(x => x.key), ['b', 'a'])
eq('then the key, so the order is stable', [row('b', same), row('a', same)].sort(S.compareSignal).map(x => x.key), ['a', 'b'])
eq('a partner row goes last whatever it would have scored', [{ key: 'bot', signal: part }, row('z', {})].sort(S.compareSignal).map(x => x.key), ['z', 'bot'])
eq('a row with no signal sorts after a ranked one', [{ key: 'none' }, row('z', {})].sort(S.compareSignal).map(x => x.key), ['z', 'none'])
eq('tier rank', [S.tierRank('high'), S.tierRank('standard'), S.tierRank(null), S.tierRank('partner')], [0, 1, 1, 2])

console.log('\nthe reason line')
eq('Jon\'s example', sc({ building: '17WEST', rate: 315, guest: 'in_house', dueInDays: -2 }).reason, '17WEST · $315 a night · guest in house · 2 days overdue')
eq('one day reads singular', sc({ building: 'Eden', rate: 84, guest: 'in_house', dueInDays: -1 }).reason, 'Eden · $84 a night · guest in house · 1 day overdue')
eq('a priority guest is named', sc({ building: 'Salato', rate: 351, guest: 'in_house', priority: true, dueInDays: 0 }).reason, 'Salato · $351 a night · priority guest in house · due today')
eq('arrivals', [sc({ guest: 'arriving_today' }).reason, sc({ guest: 'arriving_soon', arrivesInDays: 1 }).reason, sc({ guest: 'arriving_soon', arrivesInDays: 3 }).reason], ['arrival today', 'arrival tomorrow', 'arrival in 3 days'])
eq('nothing untrue is printed', sc({ building: 'Rustic' }).reason, 'Rustic')
eq('urgent with no date', sc({ building: 'Arya', rate: 151, urgent: true }).reason, 'Arya · $151 a night · urgent')
eq('a leak says what it costs', leak.reason, 'Eden · $84 a night · about $543 a week not selling')
eq('a money deadline', claim.reason, '17WEST · $315 a night · money deadline inside a day')
eq('…with its amount when there is one', sc({ building: 'Elser', stakeUsd: 450, moneyDeadlineHours: 40 }).reason, 'Elser · $450 deadline inside 48 hours')
eq('a partner says so', part.reason, 'Botanica · partner property')

console.log('\nblocked units')
eq('rate x nights', S.blockedLoss(315, 4), 1260)
eq('"about $1,260 lost"', S.lossText(1260), 'about $1,260 lost')
eq('rounded to the ten', S.lossText(1263), 'about $1,260 lost')
eq('no rate → nothing printed', S.lossText(S.blockedLoss(null, 9)), '')

console.log('\nthe inbox: priority is only the tie-break')
const Q = await import('../inbox-queue.ts')
const q = (o) => ({ tier: 0, unhappy: false, since: 1000, at: 5, ...o })
ok('a guest here now beats a priority booking coming later', Q.compareQueue(q({ tier: 0 }), q({ tier: 2, priority: true })) < 0)
ok('unhappy beats priority', Q.compareQueue(q({ unhappy: true }), q({ priority: true })) < 0)
ok('the longer wait beats priority', Q.compareQueue(q({ since: 500 }), q({ since: 900, priority: true })) < 0)
ok('all else equal, the priority booking is first', Q.compareQueue(q({ priority: true }), q({})) < 0)
ok('two priority bookings fall back to newest activity', Q.compareQueue(q({ priority: true, at: 9 }), q({ priority: true, at: 5 })) < 0)

console.log(`\n${pass} passed, ${fail} failed`)
if (fail) process.exit(1)
