// npx tsx lib/__tests__/guesty-amenities.test.mjs
const { resolveAmenity, resolveAmenities, listedUnderAnyName } = await import('../guesty-amenities.ts')
let pass = 0, fail = 0
const eq = (n, g, w) => { if (JSON.stringify(g) === JSON.stringify(w)) pass++; else { fail++; console.log('  FAIL', n, 'got', JSON.stringify(g), 'want', JSON.stringify(w)) } }
eq('exact', resolveAmenity('Kitchen'), 'Kitchen')
eq('case', resolveAmenity('kitchen'), 'Kitchen')
eq('cooking basics -> Cookware', resolveAmenity('Cooking basics'), 'Cookware')
eq('smart tv -> TV', resolveAmenity('Smart TV'), 'TV')
eq('outdoor furniture', resolveAmenity('Outdoor furniture'), 'Outdoor seating (furniture)')
eq('wifi', resolveAmenity('Wifi'), 'Wireless Internet')
eq('workspace', resolveAmenity('Dedicated workspace'), 'Laptop friendly workspace')
eq('smoke alarm', resolveAmenity('Smoke alarm'), 'Smoke detector')
eq('pool', resolveAmenity('Pool'), 'Swimming pool')
eq('colon form', resolveAmenity('Coffee maker: Keurig'), 'Coffee maker')
eq('pets has none', resolveAmenity('Pets allowed'), null)
eq('garbage', resolveAmenity('Flux capacitor'), null)
const r = resolveAmenities(['Kitchen', 'Cooking basics', 'Cookware', 'Pets allowed'])
eq('kept dedupes', r.kept, ['Kitchen', 'Cookware'])
eq('dropped', r.dropped, ['Pets allowed'])
eq('renamed', r.renamed, [{ from: 'Cooking basics', to: 'Cookware' }])
eq('listed under other name', listedUnderAnyName('Cooking basics', ['Cookware']), true)
eq('not listed', listedUnderAnyName('Smart TV', ['Cable TV']), false)
console.log(`guesty-amenities: ${pass} passed, ${fail} failed`); if (fail) process.exit(1)
